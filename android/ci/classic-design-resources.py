#!/usr/bin/env python3
"""Generates the resource overrides that bring back the classic (SESL8) look on SESL9.

The app runs on Samsung's SESL9 libraries. In the classic design, each activity's resources get
mcc=999 (see DesignChrome.wrap), which selects the res-classic/values-mcc999* folders this script
writes: every dimen, color, integer, fraction and bool whose value changed between the vendored
SESL8 and SESL9 builds, set back to its SESL8 value. Values are resolved to literals so they
don't depend on resources SESL9 removed. Run it after bumping either library:

    python3 android/ci/classic-design-resources.py
"""
import os
import re
import shutil
import sys
import tempfile
import xml.etree.ElementTree as ET
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
VENDOR = ROOT / "vendor" / "m2" / "sesl"
OUT = ROOT / "app" / "src" / "main" / "res-classic"
TYPES = ("dimen", "color", "integer", "fraction", "bool")
QUALIFIER = "mcc999"


def values_of(aar):
    """{(qualifier, type, name): text} for one AAR's simple values."""
    table = {}
    with zipfile.ZipFile(aar) as zf:
        for name in zf.namelist():
            m = re.match(r"res/(values[^/]*)/[^/]+\.xml$", name)
            if not m:
                continue
            try:
                root = ET.fromstring(zf.read(name))
            except ET.ParseError:
                continue
            for e in root:
                kind = e.get("type") if e.tag == "item" else e.tag
                if kind in TYPES and e.get("name"):
                    table[(m.group(1), kind, e.get("name"))] = (e.text or "").strip()
    return table


def pick(group, version_tag):
    hits = sorted(VENDOR.glob(f"**/{group}-*{version_tag}*.aar"))
    return hits[-1] if hits else None


def resolve(table, qualifier, kind, value, depth=0):
    """Follows @type/name references inside one library build down to a literal."""
    m = re.match(r"@(?:\*?android:)?(dimen|color|integer|fraction|bool)/(.+)$", value)
    if not m or value.startswith("@android:") or depth > 10:
        return value
    ref_kind, ref = m.group(1), m.group(2)
    for q in (qualifier, "values"):
        if (q, ref_kind, ref) in table:
            return resolve(table, q, ref_kind, table[(q, ref_kind, ref)], depth + 1)
    return None


def main():
    groups = sorted({re.sub(r"-\d.*", "", p.name) for p in VENDOR.glob("**/*.aar")})
    sesl8, sesl9 = {}, {}
    for group in groups:
        old, new = pick(group, "sesl8"), pick(group, "sesl9")
        if old and new:
            sesl8.update(values_of(old))
            sesl9.update(values_of(new))
    changed = {(t, n) for (q, t, n), v in sesl8.items()
               if any(k[1:] == (t, n) and sesl9[k] != v for k in sesl9 if k[1:] == (t, n))
               or not any(k[1:] == (t, n) for k in sesl9)}
    # Only names SESL9 still has: removed ones are never looked up.
    names9 = {(t, n) for (_, t, n) in sesl9}
    changed &= names9
    out = {}
    for (q, t, n), v in sesl8.items():
        if (t, n) not in changed:
            continue
        literal = resolve(sesl8, q, t, v)
        if literal is None or literal.startswith("?") and t != "color":
            continue
        out.setdefault(q, []).append((t, n, literal))
    if OUT.exists():
        shutil.rmtree(OUT)
    count = 0
    for q, items in sorted(out.items()):
        folder = "values-" + QUALIFIER + q[len("values"):]
        path = OUT / folder / "classic_design.xml"
        path.parent.mkdir(parents=True, exist_ok=True)
        lines = ['<?xml version="1.0" encoding="utf-8"?>',
                 "<!-- Generated by android/ci/classic-design-resources.py. Do not edit. -->",
                 '<resources xmlns:tools="http://schemas.android.com/tools" tools:ignore="all">']
        for t, n, v in sorted(items):
            tag, extra = t, ""
            if t == "integer" and not re.fullmatch(r"-?\d+|@.*", v):
                tag, extra = "item", ' type="integer" format="float"'
            v = v.replace("&", "&amp;").replace("<", "&lt;")
            lines.append(f'    <{tag} name="{n}"{extra}>{v}</{tag}>')
            count += 1
        lines.append("</resources>")
        path.write_text("\n".join(lines) + "\n")
    print(f"Wrote {count} classic overrides across {len(out)} folders into {OUT}")


if __name__ == "__main__":
    sys.exit(main())
