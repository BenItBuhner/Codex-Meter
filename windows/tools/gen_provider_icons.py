#!/usr/bin/env python3
"""Turns the Android provider vector drawables into XAML path data for the Windows app.

Android pathData uses compact SVG syntax ("a.84.84 0 0 0-.42.726", "0 011 1") that XAML's
path markup parser does not always accept, so every path is re-tokenized and written with
explicit separators. Output: src/CodexMeter.App/Assets/ProviderIcons.g.cs
"""
import pathlib, re, sys
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parents[2]
DRAWABLES = ROOT / "android/app/src/main/res/drawable"
OUT = ROOT / "windows/src/CodexMeter.App/Assets/ProviderIcons.g.cs"
NS = "{http://schemas.android.com/apk/res/android}"
NUM = re.compile(r"[-+]?(?:\d*\.\d+|\d+\.?)(?:[eE][-+]?\d+)?")
ARGS = {"M": 2, "L": 2, "H": 1, "V": 1, "C": 6, "S": 4, "Q": 4, "T": 2, "A": 7, "Z": 0}

def tokens(d):
    i = 0
    while i < len(d):
        c = d[i]
        if c.isalpha():
            yield c; i += 1
        elif c in " ,\t\n\r":
            i += 1
        else:
            m = NUM.match(d, i)
            if not m:
                raise ValueError(f"bad path near {d[i:i+20]!r}")
            yield m.group(0); i = m.end()

def normalize(d):
    out, toks, cmd = [], list(tokens(d)), None
    i = 0
    while i < len(toks):
        t = toks[i]
        if t.isalpha():
            cmd = t; out.append(t); i += 1
            if cmd.upper() == "Z":
                continue
        n = ARGS[cmd.upper()]
        if n == 0:
            continue
        args = []
        while len(args) < n:
            tok = toks[i]
            if cmd.upper() == "A" and len(args) in (3, 4) and len(tok) > 1:
                # Glued flags: "011.5" -> "0", "1", "1.5"
                args.append(tok[0]); toks[i] = tok[1:]
                continue
            args.append(tok); i += 1
        out.append(" ".join(fmt(a) for a in args))
        if cmd == "M": cmd = "L"
        if cmd == "m": cmd = "l"
        if i < len(toks) and not toks[i].isalpha():
            out.append(cmd)
    return " ".join(out)

def fmt(a):
    if a.startswith("."): return "0" + a
    if a.startswith("-."): return "-0" + a[1:]
    return a

def icon(path):
    tree = ET.parse(path).getroot()
    w, h = tree.get(NS + "viewportWidth"), tree.get(NS + "viewportHeight")
    parts, evenodd = [], False
    for p in tree.iter("path"):
        parts.append(normalize(p.get(NS + "pathData")))
        evenodd |= p.get(NS + "fillType") == "evenOdd"
    for g in tree.iter("group"):
        if any(g.get(NS + k) for k in ("scaleX", "translateX", "rotation")):
            print(f"warning: {path.name} has a transformed group", file=sys.stderr)
    return float(w), float(h), ("F0 " if evenodd else "F1 ") + " ".join(parts)

def main():
    rows = []
    for f in sorted(DRAWABLES.glob("ic_provider_*.xml")):
        pid = f.stem[len("ic_provider_"):]
        w, h, data = icon(f)
        rows.append(f'        ["{pid}"] = new({w:g}, {h:g}, "{data}"),')
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "// <auto-generated> by windows/tools/gen_provider_icons.py from the Android provider drawables.\n"
        "// Marks come from Simple Icons (CC0) and Lobe Icons (MIT) or official site icons; they are their owners' trademarks.\n"
        "namespace CodexMeter.App.Assets;\n\n"
        "internal static partial class ProviderIcons\n{\n"
        "    private static readonly Dictionary<string, (double Width, double Height, string Data)> Paths = new()\n    {\n"
        + "\n".join(rows) + "\n    };\n}\n")
    print(f"wrote {len(rows)} icons to {OUT}")

if __name__ == "__main__":
    main()
